function getElectronShells(z) {
  const caps = [2, 8, 18, 32, 32, 18, 8];
  let rem = z;
  const out = [];
  for (const c of caps) {
    if (rem <= 0) break;
    const take = Math.min(rem, c);
    out.push(take);
    rem -= take;
  }
  return out;
}

